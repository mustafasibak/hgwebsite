import { readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const photosFile = join(root, 'lib/menu-item-photos.ts')
const outFile = join(root, 'lib/menu-item-photo-versions.ts')

const source = readFileSync(photosFile, 'utf8')
const paths = [...source.matchAll(/'(\/essen\/[^']+)'/g)].map((m) => m[1])

const versions = {}
for (const src of paths) {
  const filePath = join(root, 'public', src.slice(1))
  try {
    const { mtimeMs } = statSync(filePath)
    versions[src] = String(Math.floor(mtimeMs))
  } catch {
    // Missing file — omit version so URL stays unchanged
  }
}

const lines = [
  '// Generated by scripts/generate-photo-versions.mjs — do not edit',
  'export const menuItemPhotoVersions: Record<string, string> = {',
  ...Object.entries(versions).map(([src, v]) => `  '${src}': '${v}',`),
  '}',
  '',
]

writeFileSync(outFile, lines.join('\n'))
console.log(`Wrote ${Object.keys(versions).length} photo version(s) to lib/menu-item-photo-versions.ts`)

spawnSync(process.execPath, [join(dirname(fileURLToPath(import.meta.url)), 'generate-cutout-metrics.mjs')], {
  stdio: 'inherit',
})
