import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { inflateSync } from 'node:zlib'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const photosFile = join(root, 'lib/menu-item-photos.ts')
const outFile = join(root, 'lib/cutout-photo-metrics.ts')

const TARGET_FILL = 0.58
const MIN_SCALE = 0.88
const MAX_SCALE = 1.55
const MAX_SHIFT = 14

function pngContentMetrics(filePath) {
  const buf = readFileSync(filePath)
  if (buf.toString('ascii', 1, 4) !== 'PNG') return null

  let offset = 8
  let width = 0
  let height = 0
  let colorType = 0
  const idatChunks = []

  while (offset < buf.length) {
    const length = buf.readUInt32BE(offset)
    const type = buf.toString('ascii', offset + 4, offset + 8)
    const start = offset + 8
    const chunk = buf.subarray(start, start + length)

    if (type === 'IHDR') {
      width = chunk.readUInt32BE(0)
      height = chunk.readUInt32BE(4)
      colorType = chunk[9]
    } else if (type === 'IDAT') {
      idatChunks.push(chunk)
    } else if (type === 'IEND') {
      break
    }

    offset += 12 + length
  }

  if (!width || !height || idatChunks.length === 0) return null

  const bpp = { 0: 1, 2: 3, 3: 1, 4: 2, 6: 4 }[colorType] ?? 4
  const raw = inflateSync(Buffer.concat(idatChunks))

  let idx = 0
  let minX = width
  let minY = height
  let maxX = -1
  let maxY = -1

  for (let y = 0; y < height; y += 1) {
    idx += 1
    const row = raw.subarray(idx, idx + width * bpp)
    idx += width * bpp

    for (let x = 0; x < width; x += 1) {
      const i = x * bpp
      let alpha = 255
      if (colorType === 4 || colorType === 6) alpha = row[i + 3]
      if (alpha <= 16) continue

      if (x < minX) minX = x
      if (x > maxX) maxX = x
      if (y < minY) minY = y
      if (y > maxY) maxY = y
    }
  }

  if (maxX < 0) return null

  const contentW = maxX - minX + 1
  const contentH = maxY - minY + 1
  const fill = (contentW * contentH) / (width * height)
  const cy = (minY + maxY) / 2 / height

  const scale = Math.min(MAX_SCALE, Math.max(MIN_SCALE, Math.sqrt(TARGET_FILL / fill)))
  const shift = Math.min(MAX_SHIFT, Math.max(-MAX_SHIFT, (0.5 - cy) * 100))

  return {
    scale: Math.round(scale * 1000) / 1000,
    shiftY: `${Math.round(shift * 10) / 10}%`,
  }
}

const source = readFileSync(photosFile, 'utf8')
const embedSource = readFileSync(join(root, 'components/MenuEmbed.tsx'), 'utf8')
const paths = [...new Set([
  ...[...source.matchAll(/'(\/essen\/[^']+)'/g)].map(m => m[1]),
  ...[...embedSource.matchAll(/'(\/essen\/[^']+)'/g)].map(m => m[1]),
])]

const metrics = {}
for (const src of paths) {
  const filePath = join(root, 'public', src.slice(1))
  try {
    const result = pngContentMetrics(filePath)
    if (result) metrics[src] = result
  } catch {
    // Missing or unreadable — omit
  }
}

const lines = [
  '// Generated by scripts/generate-cutout-metrics.mjs — do not edit',
  'export type CutoutPhotoMetrics = { scale: number; shiftY: string }',
  '',
  'export const cutoutPhotoMetrics: Record<string, CutoutPhotoMetrics> = {',
  ...Object.entries(metrics).map(
    ([src, { scale, shiftY }]) => `  '${src}': { scale: ${scale}, shiftY: '${shiftY}' },`,
  ),
  '}',
  '',
]

writeFileSync(outFile, lines.join('\n'))
console.log(`Wrote ${Object.keys(metrics).length} cutout metric(s) to lib/cutout-photo-metrics.ts`)
